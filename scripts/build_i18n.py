#!/usr/bin/env python3
"""Compile the reviewed UI dictionaries for extension pages and content scripts."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
locales = {locale: json.loads((ROOT / 'extension/locales' / f'{locale}.json').read_text()) for locale in ('en', 'zh-CN')}
if locales['en'].keys() != locales['zh-CN'].keys():
    raise SystemExit('Locale message keys differ')
catalog = {}
for source in sorted(locales['en']):
    placeholders = sorted(re.findall(r'\{\d+\}', source))
    for locale, messages in locales.items():
        if not isinstance(messages[source], str) or not messages[source].strip():
            raise SystemExit(f'Missing translation: {locale}: {source}')
        if sorted(re.findall(r'\{\d+\}', messages[source])) != placeholders:
            raise SystemExit(f'Placeholder mismatch: {locale}: {source}')
    catalog[source] = {locale: messages[source] for locale, messages in locales.items()}
result = '// Generated by scripts/build_i18n.py from extension/locales/*.json.\n' + '(function(root){\'use strict\';root.MSAI18nCatalog=' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';})(globalThis);\n'
target = ROOT / 'extension/i18n-data.js'
if args.check:
    if not target.exists() or target.read_text() != result:
        raise SystemExit('Stale i18n-data.js; run python3 scripts/build_i18n.py')
else:
    target.write_text(result)
print(f'{"Checked" if args.check else "Built"} {len(catalog)} messages in three interface languages')
